export const downloadStructure = () => {
  const rows: string[][] = [["Компания / Центр", "Отдел / Роль", "Сотрудник"]];
  orgData.companies.forEach((company) => {
    company.departments.forEach((dept) => {
      dept.employees.forEach((emp) => {
        rows.push([company.name, dept.name, emp]);
      });
    });
  });
  orgData.services.forEach((service) => {
    (service.employees || []).forEach((emp) => {
      rows.push([service.name, service.description, emp]);
    });
  });
  const csv = rows.map((r) => r.map((cell) => `"${cell.replace(/"/g, '""')}"`).join(";")).join("\n");
  const blob = new Blob(["\uFEFF" + csv], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "org-structure.csv";
  a.click();
  URL.revokeObjectURL(url);
};